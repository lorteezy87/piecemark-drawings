/**
 * Demo data for the PM tracker. Dates are generated relative to today so the
 * 48-hour and 10-day look ahead always has something in it when a new station
 * opens the app for the first time.
 */
function d(offsetDays: number): string {
  const t = new Date();
  t.setHours(12, 0, 0, 0);
  t.setDate(t.getDate() + offsetDays);
  return t.toISOString().slice(0, 10);
}

